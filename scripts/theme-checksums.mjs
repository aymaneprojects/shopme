// Writes packages/theme-default/checksums.json: for every file the default theme has ever shipped (any commit of
// packages/theme-default, plus the working tree), the MD5 of each published text and binary, in English and with the
// French seed texts that a French shop gets at install.
//
// Themes installed before ShopMe recorded the checksums of the files it installed (themes.origin_checksums) are
// compared with this list when they are updated: a file whose checksum is listed was not edited by the merchant.
//
//   node scripts/theme-checksums.mjs
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = 'packages/theme-default';
const DIRS = ['layout', 'templates', 'sections', 'blocks', 'snippets', 'config', 'locales', 'assets'];
const TEXT = new Set(['.liquid', '.json', '.css', '.js', '.mjs', '.svg', '.txt', '.html']);
const BINARY = new Set(['.png', '.jpg', '.jpeg', '.gif', '.webp', '.avif', '.ico', '.woff', '.woff2', '.ttf', '.otf', '.eot', '.mp4', '.webm', '.mp3']);

const git = (...args) => execFileSync('git', args, { cwd: root, maxBuffer: 256 * 1024 * 1024 });
const md5 = (data) => createHash('md5').update(data).digest('hex');
const kind = (p) => {
  const ext = path.extname(p).toLowerCase();
  if (!DIRS.includes(p.split('/')[0])) return null;
  if (TEXT.has(ext)) return 'text';
  return p.startsWith('assets/') && BINARY.has(ext) ? 'binary' : null;
};

/** Same replacement as localizeSeedTexts in packages/core/src/services/theme-install.ts. */
function localize(p, body, seeds) {
  if (p.startsWith('locales/') || !/\.(liquid|json)$/.test(p)) return body;
  for (const [en, fr] of Object.entries(seeds)) body = body.split(JSON.stringify(en)).join(JSON.stringify(fr));
  return body;
}

const known = new Map();
const add = (p, sum) => { if (!known.has(p)) known.set(p, new Set()); known.get(p).add(sum); };

/** Record one state of the theme: `files` maps a theme path to its raw bytes. */
function record(files) {
  let seeds = {};
  try { seeds = JSON.parse(files.get('locales/fr.json')?.toString('utf8') ?? '{}').seed_defaults ?? {}; } catch { /* no French seed texts */ }
  for (const [p, data] of files) {
    if (kind(p) === 'binary') { add(p, md5(data)); continue; }
    const body = data.toString('utf8');
    add(p, md5(body));
    add(p, md5(localize(p, body, seeds)));
  }
}

const commits = git('rev-list', '--full-history', 'HEAD', '--', pkg).toString().trim().split('\n').filter(Boolean);
for (const c of commits) {
  const files = new Map();
  for (const line of git('ls-tree', '-r', c, '--', `${pkg}/`).toString().trim().split('\n').filter(Boolean)) {
    const [meta, full] = line.split('\t');
    const rel = full.slice(pkg.length + 1);
    if (kind(rel)) files.set(rel, git('cat-file', 'blob', meta.split(' ')[2]));
  }
  record(files);
}

// The working tree (what this checkout installs today).
const tree = new Map();
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) walk(full);
    else {
      const rel = path.relative(path.join(root, pkg), full).split(path.sep).join('/');
      if (kind(rel)) tree.set(rel, readFileSync(full));
    }
  }
};
for (const d of DIRS) if (existsSync(path.join(root, pkg, d))) walk(path.join(root, pkg, d));
record(tree);

const files = Object.fromEntries([...known].sort(([a], [b]) => a.localeCompare(b)).map(([p, s]) => [p, [...s].sort()]));
const out = { about: 'MD5 of every file the default theme has shipped, to tell merchant edits apart in themes installed before ShopMe recorded them. Generated by scripts/theme-checksums.mjs.', files };
writeFileSync(path.join(root, pkg, 'checksums.json'), `${JSON.stringify(out, null, 1)}\n`);
console.log(`${Object.keys(files).length} files, ${Object.values(files).reduce((n, s) => n + s.length, 0)} checksums from ${commits.length} commits`);
