#!/usr/bin/env node
// Builds the time zone -> country table used to place live visitors on the map, from the IANA time zone database
// (`zone.tab`, `zone1970.tab` and the links of `tzdata.zi`, all in the public domain).
//
//   node scripts/gen-tz-countries.mjs [tzdata dir, default /usr/share/zoneinfo]
//
// Writes packages/core/src/services/analytics/tz-countries.ts (zone -> ISO 3166 country) and
// apps/admin/src/lib/country-points.ts (one representative point per country, used when the world map has no shape for it).
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const dir = process.argv[2] ?? '/usr/share/zoneinfo';
const root = path.resolve(import.meta.dirname, '..');
const rows = (file) => readFileSync(path.join(dir, file), 'utf8').split('\n').filter((l) => l && !l.startsWith('#')).map((l) => l.split('\t'));

const zone = new Map(); // zone name -> country
const points = new Map(); // country -> [lon, lat] of its first listed zone
const coord = (s) => {
  const m = /^([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$/.exec(s);
  if (!m) return null;
  const dms = (sign, d, mm, ss) => (sign === '-' ? -1 : 1) * (Number(d) + Number(mm) / 60 + Number(ss ?? 0) / 3600);
  return [Math.round(dms(m[5], m[6], m[7], m[8]) * 100) / 100, Math.round(dms(m[1], m[2], m[3], m[4]) * 100) / 100];
};
for (const [cc, at, tz] of rows('zone.tab')) {
  zone.set(tz, cc);
  if (!points.has(cc)) { const p = coord(at); if (p) points.set(cc, p); }
}
// zone1970.tab can list zones zone.tab lacks; the first country of the row is the main one.
for (const [ccs, , tz] of rows('zone1970.tab')) if (!zone.has(tz)) zone.set(tz, ccs.split(',')[0]);
// Links (old names, such as Asia/Calcutta or US/Eastern, which browsers still report) take the country of their target.
const zi = readFileSync(path.join(dir, 'tzdata.zi'), 'utf8');
const version = /^# version (\S+)/m.exec(zi)?.[1] ?? 'unknown';
for (const line of zi.split('\n')) {
  const m = /^L (\S+) (\S+)$/.exec(line);
  if (m && !zone.has(m[2]) && zone.has(m[1])) zone.set(m[2], zone.get(m[1]));
}

const byCountry = new Map();
for (const [tz, cc] of [...zone].sort((a, b) => a[0].localeCompare(b[0]))) byCountry.set(cc, [...(byCountry.get(cc) ?? []), tz]);
const countries = [...byCountry.keys()].sort();

const core = `// Generated by scripts/gen-tz-countries.mjs from the IANA time zone database ${version} (zone.tab, zone1970.tab, tzdata.zi links),
// which is in the public domain. Do not edit by hand: run the script again with a newer tzdata.

/** Version of the time zone database the table was built from. */
export const TZ_DATA_VERSION = '${version}';

/** Time zones of each country (space separated). */
const ZONES: Record<string, string> = {
${countries.map((cc) => `  ${cc}: '${byCountry.get(cc).join(' ')}',`).join('\n')}
};

let index: Map<string, string> | null = null;

/**
 * The ISO 3166 country of an IANA time zone name, such as \`FR\` for \`Europe/Paris\`, or null when the zone is not tied to a
 * country (\`UTC\`, \`Etc/GMT+2\`) or unknown. Old names that browsers still report (\`Asia/Calcutta\`) are understood.
 */
export function countryForTimeZone(tz: unknown): string | null {
  if (typeof tz !== 'string' || tz.length > 64) return null;
  if (!index) {
    index = new Map();
    for (const [cc, zones] of Object.entries(ZONES)) for (const z of zones.split(' ')) index.set(z.toLowerCase(), cc);
  }
  return index.get(tz.trim().toLowerCase()) ?? null;
}
`;
writeFileSync(path.join(root, 'packages/core/src/services/analytics/tz-countries.ts'), core);

const admin = `// Generated by scripts/gen-tz-countries.mjs from the coordinates of the IANA time zone database ${version} (zone.tab, public domain).
// One point (longitude, latitude) per country: where the live view map puts a country it has no shape for.
export const COUNTRY_POINTS: Record<string, [number, number]> = {
${[...points].sort((a, b) => a[0].localeCompare(b[0])).map(([cc, [lon, lat]]) => `  ${cc}: [${lon}, ${lat}],`).join('\n')}
};
`;
writeFileSync(path.join(root, 'apps/admin/src/lib/country-points.ts'), admin);
console.log(`tzdata ${version}: ${zone.size} zones, ${countries.length} countries`);
