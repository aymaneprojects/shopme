/** Quote a CSV cell (RFC 4180). */
const cell = (v: unknown) => { const s = v === null || v === undefined ? '' : String(v); return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s; };

export const toCsv = (rows: unknown[][]) => `${rows.map((r) => r.map(cell).join(',')).join('\r\n')}\r\n`;

/** Hand a text file to the browser as a download. */
export function downloadText(filename: string, text: string, type = 'text/csv;charset=utf-8') {
  const url = URL.createObjectURL(new Blob([text], { type }));
  const a = document.createElement('a');
  a.href = url; a.download = filename;
  document.body.append(a); a.click(); a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
